    fn run_assembly(assembly: &str) -> i32 {
        let program = assemble(assembly).unwrap_or_else(|error| {
            panic!("generated assembly did not assemble: {error:?}\n{assembly}")
        });
        let mut pipeline = Pipeline::new(program);
        assert!(pipeline.run(1_000_000), "program did not halt:\n{assembly}");
        pipeline.snapshot().registers[10] as i32
    }

