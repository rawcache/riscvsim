use super::hir::{
    typed_hir_from_rust, HirBinding, HirFunction, HirType, HirTypeAnnotation, TypedHir,
};
use super::identifiers::{identifier_map, IdentifierTarget};
use super::{
    ArrayInitProvenance, AssignmentProvenance, Expr, Func, IfOrigin, LValue, LoopKind, Stmt,
    TranslateError,
};
use std::collections::{HashMap, HashSet};
use std::fmt::Write as _;

pub(super) fn translate(source: &str) -> Result<String, TranslateError> {
    let hir = typed_hir_from_rust(source)?;
    Emitter::new(&hir, TargetDialect::C)?.emit()
}

pub(super) fn translate_cpp(source: &str) -> Result<String, TranslateError> {
    let hir = typed_hir_from_rust(source)?;
    Emitter::new(&hir, TargetDialect::Cpp)?.emit()
}

pub(super) fn validate(hir: &TypedHir) -> Result<(), TranslateError> {
    // The emitter's type walk is the authoritative Rust subset validator.
    // Discarding its text keeps RV32/RV64 compilation on exactly the same
    // accepted-language boundary without duplicating semantic rules.
    Emitter::new(hir, TargetDialect::C)?.emit().map(|_| ())
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum TargetDialect {
    C,
    Cpp,
}

#[derive(Clone)]
struct Signature {
    parameters: Vec<HirType>,
    result: HirType,
}

struct Emitter<'a> {
    hir: &'a TypedHir,
    signatures: HashMap<String, Signature>,
    names: HashMap<String, String>,
    out: String,
    reserved: HashSet<String>,
    range_counter: usize,
    loop_depth: usize,
    target: TargetDialect,
}

impl<'a> Emitter<'a> {
    fn new(hir: &'a TypedHir, target: TargetDialect) -> Result<Self, TranslateError> {
        let mut signatures = HashMap::new();
        for function in &hir.ast.funcs {
            if signatures
                .insert(
                    function.name.clone(),
                    Signature {
                        parameters: function
                            .param_types
                            .iter()
                            .copied()
                            .map(Into::into)
                            .collect(),
                        result: function.return_type.into(),
                    },
                )
                .is_some()
            {
                return Err(TranslateError::new(
                    function.line,
                    format!("function '{}' is defined twice", function.name),
                ));
            }
        }
        let names = identifier_map(
            hir.ast
                .funcs
                .iter()
                .map(|function| function.name.as_str())
                .chain(hir.functions.iter().flat_map(|function| {
                    function
                        .bindings
                        .iter()
                        .map(|binding| binding.name.as_str())
                })),
            match target {
                TargetDialect::C => IdentifierTarget::C,
                TargetDialect::Cpp => IdentifierTarget::Cpp,
            },
        );
        Ok(Self {
            hir,
            signatures,
            names,
            out: String::new(),
            reserved: HashSet::new(),
            range_counter: 0,
            loop_depth: 0,
            target,
        })
    }

    fn emit(mut self) -> Result<String, TranslateError> {
        let target = if self.target == TargetDialect::C {
            "C"
        } else {
            "C++"
        };
        let _ = writeln!(
            self.out,
            "// Generated by the StudyRISC-V Rust-to-{target} translator."
        );
        self.out
            .push_str("// Compilable within the documented integer subset.\n\n");
        for function in &self.hir.ast.funcs {
            let _ = writeln!(self.out, "{};", self.signature(function));
        }
        self.out.push('\n');
        for (index, function) in self.hir.ast.funcs.iter().enumerate() {
            if index > 0 {
                self.out.push('\n');
            }
            self.emit_function(function)?;
        }
        Ok(self.out)
    }

    fn signature(&self, function: &Func) -> String {
        let parameters = function
            .params
            .iter()
            .zip(&function.param_types)
            .map(|(name, value_type)| {
                format!(
                    "{} {}",
                    self.target_type((*value_type).into()),
                    self.target_name(name)
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        format!(
            "{} {}({parameters})",
            self.target_type(function.return_type.into()),
            self.target_name(&function.name)
        )
    }

    fn emit_function(&mut self, function: &Func) -> Result<(), TranslateError> {
        self.reserved = self.names.values().cloned().collect();
        self.range_counter = 0;
        self.loop_depth = 0;
        let return_type: HirType = function.return_type.into();
        if return_type != HirType::Unit && block_flow(&function.body).falls_through {
            return Err(TranslateError::new(
                function.line,
                format!(
                    "function '{}' can fall through without returning {}",
                    function.name,
                    type_name(return_type)
                ),
            ));
        }
        let _ = writeln!(self.out, "{} {{", self.signature(function));
        self.emit_statements(function, &function.body, 1)?;
        match (self.target, return_type) {
            (TargetDialect::C, _) | (_, HirType::I32) => self.out.push_str("    return 0;\n"),
            (TargetDialect::Cpp, HirType::Bool) => self.out.push_str("    return false;\n"),
            (TargetDialect::Cpp, HirType::Unit) => {}
        }
        self.out.push_str("}\n");
        Ok(())
    }

    fn emit_statements(
        &mut self,
        function: &Func,
        statements: &[Stmt],
        depth: usize,
    ) -> Result<(), TranslateError> {
        for statement in statements {
            self.emit_statement(function, statement, depth)?;
        }
        Ok(())
    }

    fn emit_statement(
        &mut self,
        function: &Func,
        statement: &Stmt,
        depth: usize,
    ) -> Result<(), TranslateError> {
        let indent = "    ".repeat(depth);
        match statement {
            Stmt::Decl(name, initial, source, line) => {
                let initial = initial.as_ref().ok_or_else(|| {
                    TranslateError::new(*line, "Rust bindings require an initializer")
                })?;
                let expected = source
                    .declared_type
                    .map(Into::into)
                    .unwrap_or(self.binding_type(function, name, *line)?);
                if expected == HirType::Unit {
                    return Err(TranslateError::new(
                        *line,
                        "Rust subset bindings support only i32 and bool values, not unit",
                    ));
                }
                let actual = self.expression_type(function, initial)?;
                self.require_type(*line, expected, actual, "binding initializer")?;
                let value = self.expression(function, initial)?;
                let annotation = self.lookup_binding(function, name, *line)?.annotation;
                let name = self.target_name(name);
                let keyword = if self.target == TargetDialect::Cpp
                    && annotation == HirTypeAnnotation::Inferred
                {
                    "auto"
                } else {
                    self.target_type(expected)
                };
                let _ = writeln!(self.out, "{indent}{keyword} {name} = {value};");
            }
            Stmt::DeclArray(name, size, initial, _, initializer, line) => {
                let mut values = Vec::with_capacity(initial.len());
                for value in initial {
                    let actual = self.expression_type(function, value)?;
                    self.require_type(*line, HirType::I32, actual, "array initializer")?;
                    values.push(self.expression(function, value)?);
                }
                match initializer {
                    ArrayInitProvenance::Repeat => {
                        let value = values.first().ok_or_else(|| {
                            TranslateError::new(*line, "Rust repeat initializer is empty")
                        })?;
                        let temporary = self.fresh_range_name("repeat");
                        let _ = writeln!(self.out, "{indent}int {temporary} = {value};");
                        let repeated = vec![temporary; *size].join(", ");
                        let name = self.target_name(name);
                        let _ = writeln!(self.out, "{indent}int {name}[{size}] = {{{repeated}}};");
                    }
                    ArrayInitProvenance::List => {
                        let name = self.target_name(name);
                        let _ = writeln!(
                            self.out,
                            "{indent}int {name}[{size}] = {{{}}};",
                            values.join(", ")
                        );
                    }
                    ArrayInitProvenance::Absent => {
                        return Err(TranslateError::new(
                            *line,
                            "internal: Rust array declaration has no initializer",
                        ));
                    }
                }
            }
            Stmt::Expr(expression, _) => {
                self.expression_type(function, expression)?;
                let expression = self.expression(function, expression)?;
                let _ = writeln!(self.out, "{indent}{expression};");
            }
            Stmt::If(_, body, _, source) if source.origin == IfOrigin::PlainBlock => {
                let _ = writeln!(self.out, "{indent}{{");
                self.emit_statements(function, body, depth + 1)?;
                let _ = writeln!(self.out, "{indent}}}");
            }
            Stmt::If(condition, body, otherwise, _) => {
                self.require_condition(function, condition)?;
                let condition = self.expression(function, condition)?;
                let _ = writeln!(self.out, "{indent}if ({condition}) {{");
                self.emit_statements(function, body, depth + 1)?;
                if otherwise.is_empty() {
                    let _ = writeln!(self.out, "{indent}}}");
                } else {
                    let _ = writeln!(self.out, "{indent}}} else {{");
                    self.emit_statements(function, otherwise, depth + 1)?;
                    let _ = writeln!(self.out, "{indent}}}");
                }
            }
            Stmt::While(condition, body, source) => {
                if source.kind != LoopKind::RustLoop {
                    self.require_condition(function, condition)?;
                }
                let condition = if source.kind == LoopKind::RustLoop {
                    if self.target == TargetDialect::Cpp {
                        "true".to_string()
                    } else {
                        "1".to_string()
                    }
                } else {
                    self.expression(function, condition)?
                };
                let _ = writeln!(self.out, "{indent}while ({condition}) {{");
                self.loop_depth += 1;
                let body_result = self.emit_statements(function, body, depth + 1);
                self.loop_depth -= 1;
                body_result?;
                let _ = writeln!(self.out, "{indent}}}");
            }
            Stmt::For(initial, condition, _, body, source)
                if source.kind == LoopKind::RustRange =>
            {
                let (iterator, start, line) = range_start(initial)?;
                let end = range_end(condition, &iterator)?;
                self.require_type(
                    line,
                    HirType::I32,
                    self.expression_type(function, start)?,
                    "range start",
                )?;
                self.require_type(
                    line,
                    HirType::I32,
                    self.expression_type(function, end)?,
                    "range end",
                )?;
                let start_name = self.fresh_range_name("start");
                let end_name = self.fresh_range_name("end");
                let iterator = self.target_name(iterator);
                let start = self.expression(function, start)?;
                let end = self.expression(function, end)?;
                let _ = writeln!(self.out, "{indent}int {start_name} = {start};");
                let _ = writeln!(self.out, "{indent}int {end_name} = {end};");
                let _ = writeln!(
                    self.out,
                    "{indent}for (int {iterator} = {start_name}; {iterator} < {end_name}; {iterator} = {iterator} + 1) {{"
                );
                self.loop_depth += 1;
                let body_result = self.emit_statements(function, body, depth + 1);
                self.loop_depth -= 1;
                body_result?;
                let _ = writeln!(self.out, "{indent}}}");
            }
            Stmt::For(_, _, _, _, _) => {
                return Err(TranslateError::new(
                    0,
                    "internal: Rust AST contains a non-range for loop",
                ));
            }
            Stmt::Return(value, _, line) => {
                let expected = function.return_type.into();
                match value {
                    Some(value) => {
                        let actual = self.expression_type(function, value)?;
                        self.require_type(*line, expected, actual, "return value")?;
                        let value = self.expression(function, value)?;
                        let _ = writeln!(self.out, "{indent}return {value};");
                    }
                    None if expected == HirType::Unit => {
                        let value = if self.target == TargetDialect::Cpp {
                            "return;"
                        } else {
                            "return 0;"
                        };
                        let _ = writeln!(self.out, "{indent}{value}");
                    }
                    None => {
                        return Err(TranslateError::new(
                            *line,
                            "value-returning functions require a return value",
                        ));
                    }
                }
            }
            Stmt::Break(line) => {
                if self.loop_depth == 0 {
                    return Err(TranslateError::new(*line, "break outside a loop"));
                }
                let _ = writeln!(self.out, "{indent}break;");
            }
            Stmt::Continue(line) => {
                if self.loop_depth == 0 {
                    return Err(TranslateError::new(*line, "continue outside a loop"));
                }
                let _ = writeln!(self.out, "{indent}continue;");
            }
        }
        Ok(())
    }

    fn expression(&self, function: &Func, expression: &Expr) -> Result<String, TranslateError> {
        Ok(match expression {
            Expr::Num(value, value_type, _) => {
                if self.target == TargetDialect::Cpp && *value_type == super::ScalarType::Bool {
                    (*value != 0).to_string()
                } else {
                    value.to_string()
                }
            }
            Expr::Var(name, _) => self.target_name(name),
            Expr::Index(name, index, _) => {
                let index = match &**index {
                    Expr::Unary("as usize", value, _) => value,
                    _ => index,
                };
                format!(
                    "{}[{}]",
                    self.target_name(name),
                    self.expression(function, index)?
                )
            }
            Expr::Unary(operator, value, _) => {
                if *operator == "as usize" {
                    return self.expression(function, value);
                }
                let operator =
                    if *operator == "!" && self.expression_type(function, value)? == HirType::I32 {
                        "~"
                    } else {
                        operator
                    };
                format!("({operator}{})", self.expression(function, value)?)
            }
            Expr::Binary(operator, left, right, _) => {
                let rendered = format!(
                    "({} {operator} {})",
                    self.expression(function, left)?,
                    self.expression(function, right)?
                );
                if self.target == TargetDialect::Cpp
                    && matches!(*operator, "&" | "|" | "^")
                    && self.expression_type(function, expression)? == HirType::Bool
                {
                    format!("(!(!{rendered}))")
                } else {
                    rendered
                }
            }
            Expr::Assign(target, value, source, _) => {
                let target = self.lvalue(function, target)?;
                let value = self.expression(function, value)?;
                match source {
                    AssignmentProvenance::Simple => format!("({target} = {value})"),
                    AssignmentProvenance::Compound(operator) => {
                        format!("({target} {operator}= {value})")
                    }
                    AssignmentProvenance::PrefixIncrement
                    | AssignmentProvenance::PrefixDecrement
                    | AssignmentProvenance::PostfixIncrement
                    | AssignmentProvenance::PostfixDecrement => {
                        return Err(TranslateError::new(
                            expression_line(expression),
                            "internal: Rust AST contains C increment syntax",
                        ));
                    }
                }
            }
            Expr::Call(name, arguments, _) => format!(
                "{}({})",
                self.target_name(name),
                arguments
                    .iter()
                    .map(|argument| self.expression(function, argument))
                    .collect::<Result<Vec<_>, _>>()?
                    .join(", ")
            ),
        })
    }

    fn lvalue(&self, function: &Func, target: &LValue) -> Result<String, TranslateError> {
        Ok(match target {
            LValue::Var(name, _) => self.target_name(name),
            LValue::Index(name, index, _) => {
                format!(
                    "{}[{}]",
                    self.target_name(name),
                    self.expression(function, index)?
                )
            }
        })
    }

    fn expression_type(
        &self,
        function: &Func,
        expression: &Expr,
    ) -> Result<HirType, TranslateError> {
        let line = expression_line(expression);
        match expression {
            Expr::Num(_, value_type, _) => Ok((*value_type).into()),
            Expr::Var(name, line) => self.lookup_type(function, name, *line),
            Expr::Index(name, index, line) => {
                self.lookup_array(function, name, *line)?;
                let index_type = match &**index {
                    Expr::Unary("as usize", value, _) => self.expression_type(function, value)?,
                    _ => self.expression_type(function, index)?,
                };
                self.require_type(*line, HirType::I32, index_type, "array index")?;
                Ok(HirType::I32)
            }
            Expr::Unary(operator, value, _) => {
                let value_type = self.expression_type(function, value)?;
                match *operator {
                    "as usize" => Err(type_error(
                        line,
                        "'as usize' casts are only supported directly inside array indexes",
                    )),
                    "-" | "~" => {
                        self.require_type(line, HirType::I32, value_type, "unary operand")?;
                        Ok(HirType::I32)
                    }
                    "!" if matches!(value_type, HirType::I32 | HirType::Bool) => Ok(value_type),
                    _ => Err(type_error(line, "unsupported unary operand type")),
                }
            }
            Expr::Binary(operator, left, right, _) => {
                let left_type = self.expression_type(function, left)?;
                let right_type = self.expression_type(function, right)?;
                match *operator {
                    "&&" | "||" => {
                        self.require_pair(line, HirType::Bool, left_type, right_type)?;
                        Ok(HirType::Bool)
                    }
                    "==" | "!=" => {
                        self.require_type(line, left_type, right_type, "comparison operand")?;
                        Ok(HirType::Bool)
                    }
                    "<" | "<=" | ">" | ">=" => {
                        self.require_pair(line, HirType::I32, left_type, right_type)?;
                        Ok(HirType::Bool)
                    }
                    "&" | "|" | "^" if left_type == right_type => Ok(left_type),
                    "+" | "-" | "*" | "/" | "%" | "<<" | ">>" | "&" | "|" | "^" => {
                        self.require_pair(line, HirType::I32, left_type, right_type)?;
                        Ok(HirType::I32)
                    }
                    _ => Err(type_error(line, "unsupported binary operand types")),
                }
            }
            Expr::Assign(target, value, _, _) => {
                let target_type = self.lvalue_type(function, target)?;
                let value_type = self.expression_type(function, value)?;
                self.require_type(line, target_type, value_type, "assignment")?;
                Ok(HirType::Unit)
            }
            Expr::Call(name, arguments, line) => {
                let signature = self.signatures.get(name).ok_or_else(|| {
                    TranslateError::new(*line, format!("call to undefined function '{name}'"))
                })?;
                if arguments.len() != signature.parameters.len() {
                    return Err(TranslateError::new(
                        *line,
                        format!(
                            "function '{name}' expects {} arguments, found {}",
                            signature.parameters.len(),
                            arguments.len()
                        ),
                    ));
                }
                for (argument, expected) in arguments.iter().zip(&signature.parameters) {
                    let actual = self.expression_type(function, argument)?;
                    self.require_type(*line, *expected, actual, "function argument")?;
                }
                Ok(signature.result)
            }
        }
    }

    fn lvalue_type(&self, function: &Func, target: &LValue) -> Result<HirType, TranslateError> {
        match target {
            LValue::Var(name, line) => self.lookup_type(function, name, *line),
            LValue::Index(name, index, line) => {
                self.lookup_array(function, name, *line)?;
                let index_type = match index {
                    Expr::Unary("as usize", value, _) => self.expression_type(function, value)?,
                    _ => self.expression_type(function, index)?,
                };
                self.require_type(*line, HirType::I32, index_type, "array index")?;
                Ok(HirType::I32)
            }
        }
    }

    fn require_condition(&self, function: &Func, condition: &Expr) -> Result<(), TranslateError> {
        let actual = self.expression_type(function, condition)?;
        self.require_type(
            expression_line(condition),
            HirType::Bool,
            actual,
            "condition",
        )
    }

    fn require_pair(
        &self,
        line: usize,
        expected: HirType,
        left: HirType,
        right: HirType,
    ) -> Result<(), TranslateError> {
        self.require_type(line, expected, left, "left operand")?;
        self.require_type(line, expected, right, "right operand")
    }

    fn require_type(
        &self,
        line: usize,
        expected: HirType,
        actual: HirType,
        context: &str,
    ) -> Result<(), TranslateError> {
        if expected == actual {
            Ok(())
        } else {
            Err(TranslateError::new(
                line,
                format!(
                    "invalid Rust subset type: {context} requires {}, found {}",
                    type_name(expected),
                    type_name(actual)
                ),
            ))
        }
    }

    fn lookup_type(
        &self,
        function: &Func,
        name: &str,
        line: usize,
    ) -> Result<HirType, TranslateError> {
        let binding = self.lookup_binding(function, name, line)?;
        if binding.array_len.is_some() {
            return Err(TranslateError::new(
                line,
                format!(
                    "'{name}' is an array and can only be used with an index; arrays can only be indexed here"
                ),
            ));
        }
        Ok(binding.value_type)
    }

    fn lookup_array(&self, function: &Func, name: &str, line: usize) -> Result<(), TranslateError> {
        if self
            .lookup_binding(function, name, line)?
            .array_len
            .is_none()
        {
            return Err(TranslateError::new(
                line,
                format!("'{name}' is not an array"),
            ));
        }
        Ok(())
    }

    fn lookup_binding(
        &self,
        function: &Func,
        name: &str,
        line: usize,
    ) -> Result<&HirBinding, TranslateError> {
        self.function_hir(&function.name)
            .bindings
            .iter()
            .find(|binding| binding.name == name)
            .ok_or_else(|| TranslateError::new(line, format!("binding '{name}' is not declared")))
    }

    fn binding_type(
        &self,
        function: &Func,
        name: &str,
        line: usize,
    ) -> Result<HirType, TranslateError> {
        Ok(self.lookup_binding(function, name, line)?.value_type)
    }

    fn function_hir(&self, name: &str) -> &HirFunction {
        self.hir
            .functions
            .iter()
            .find(|function| function.name == name)
            .expect("HIR function must match AST")
    }

    fn fresh_range_name(&mut self, role: &str) -> String {
        loop {
            let name = format!("riscvsim_range_{role}_{}", self.range_counter);
            self.range_counter += 1;
            if self.reserved.insert(name.clone()) {
                return name;
            }
        }
    }

    fn target_name(&self, name: &str) -> String {
        self.names
            .get(name)
            .cloned()
            .unwrap_or_else(|| name.to_string())
    }

    fn target_type(&self, value_type: HirType) -> &'static str {
        match (self.target, value_type) {
            (TargetDialect::Cpp, HirType::Bool) => "bool",
            (TargetDialect::Cpp, HirType::Unit) => "void",
            _ => "int",
        }
    }
}

#[derive(Clone, Copy)]
struct Flow {
    falls_through: bool,
    breaks_current_loop: bool,
}

fn block_flow(statements: &[Stmt]) -> Flow {
    let mut flow = Flow {
        falls_through: true,
        breaks_current_loop: false,
    };
    for statement in statements {
        if !flow.falls_through {
            break;
        }
        let statement = statement_flow(statement);
        flow.breaks_current_loop |= statement.breaks_current_loop;
        flow.falls_through = statement.falls_through;
    }
    flow
}

fn statement_flow(statement: &Stmt) -> Flow {
    match statement {
        Stmt::Return(..) => Flow {
            falls_through: false,
            breaks_current_loop: false,
        },
        Stmt::Break(_) => Flow {
            falls_through: false,
            breaks_current_loop: true,
        },
        Stmt::Continue(_) => Flow {
            falls_through: false,
            breaks_current_loop: false,
        },
        Stmt::If(_, body, _, source) if source.origin == IfOrigin::PlainBlock => block_flow(body),
        Stmt::If(_, body, otherwise, _) => {
            let then_flow = block_flow(body);
            let else_flow = if otherwise.is_empty() {
                Flow {
                    falls_through: true,
                    breaks_current_loop: false,
                }
            } else {
                block_flow(otherwise)
            };
            Flow {
                falls_through: then_flow.falls_through || else_flow.falls_through,
                breaks_current_loop: then_flow.breaks_current_loop || else_flow.breaks_current_loop,
            }
        }
        Stmt::While(_, body, source) if source.kind == LoopKind::RustLoop => Flow {
            falls_through: block_flow(body).breaks_current_loop,
            breaks_current_loop: false,
        },
        Stmt::While(..) | Stmt::For(..) => Flow {
            falls_through: true,
            breaks_current_loop: false,
        },
        Stmt::Decl(..) | Stmt::DeclArray(..) | Stmt::Expr(..) => Flow {
            falls_through: true,
            breaks_current_loop: false,
        },
    }
}

fn range_start(initial: &Option<Box<Stmt>>) -> Result<(&str, &Expr, usize), TranslateError> {
    match initial.as_deref() {
        Some(Stmt::Decl(name, Some(start), _, line)) => Ok((name, start, *line)),
        _ => Err(TranslateError::new(
            0,
            "internal: malformed Rust range initializer",
        )),
    }
}

fn range_end<'a>(condition: &'a Option<Expr>, iterator: &str) -> Result<&'a Expr, TranslateError> {
    match condition {
        Some(Expr::Binary("<", left, end, _)) if matches!(&**left, Expr::Var(name, _) if name == iterator) => {
            Ok(end)
        }
        _ => Err(TranslateError::new(
            0,
            "internal: malformed Rust range condition",
        )),
    }
}

fn expression_line(expression: &Expr) -> usize {
    match expression {
        Expr::Var(_, line) | Expr::Index(_, _, line) | Expr::Call(_, _, line) => *line,
        Expr::Num(_, _, line)
        | Expr::Unary(_, _, line)
        | Expr::Binary(_, _, _, line)
        | Expr::Assign(_, _, _, line) => *line,
    }
}

fn type_name(value_type: HirType) -> &'static str {
    match value_type {
        HirType::I32 => "i32",
        HirType::Bool => "bool",
        HirType::Unit => "unit",
    }
}

fn type_error(line: usize, message: &str) -> TranslateError {
    TranslateError::new(line, format!("invalid Rust subset type: {message}"))
}

