    fn run_rv32(assembly: &str) -> i32 {
        let program = assemble(assembly).unwrap_or_else(|errors| {
            panic!("generated RV32 did not assemble: {errors:?}\n{assembly}")
        });
        let mut pipeline = Pipeline::new(program);
        assert!(pipeline.run(1_000_000), "RV32 did not halt:\n{assembly}");
        let halt = pipeline.snapshot().halt.expect("missing RV32 halt state");
        assert_eq!(halt.kind, "complete", "RV32 trapped: {}", halt.message);
        pipeline.registers()[10] as i32
    }

    fn run_rv64(assembly: &str) -> i32 {
        let program = assemble64(assembly).unwrap_or_else(|errors| {
            panic!("generated RV64 did not assemble: {errors:?}\n{assembly}")
        });
        let mut pipeline = Pipeline64::new(program);
        assert!(pipeline.run(1_000_000), "RV64 did not halt:\n{assembly}");
        let halt = pipeline.snapshot().halt.expect("missing RV64 halt state");
        assert_eq!(halt.kind, "complete", "RV64 trapped: {}", halt.message);
        pipeline.registers()[10] as u32 as i32
    }

    fn assert_equivalent(source: &str, expected: i32) -> String {
        let rust = translate(source).unwrap_or_else(|error| {
            panic!(
                "C++-to-Rust failed at line {}: {}",
                error.line, error.message
            )
        });
        let cpp32 = super::super::cpp_to_asm(source).expect("C++ RV32 compilation failed");
        let rust32 = super::super::rust_to_asm(&rust)
            .unwrap_or_else(|error| panic!("generated Rust RV32 failed: {error:?}\n{rust}"));
        let cpp64 = super::super::cpp_to_asm64(source).expect("C++ RV64 compilation failed");
        let rust64 = super::super::rust_to_asm64(&rust)
            .unwrap_or_else(|error| panic!("generated Rust RV64 failed: {error:?}\n{rust}"));
        assert_eq!(run_rv32(&cpp32), expected, "unexpected C++ RV32 result");
        assert_eq!(
            run_rv32(&rust32),
            expected,
            "unexpected Rust RV32 result\n{rust}"
        );
        assert_eq!(run_rv64(&cpp64), expected, "unexpected C++ RV64 result");
        assert_eq!(
            run_rv64(&rust64),
            expected,
            "unexpected Rust RV64 result\n{rust}"
        );
        rust
    }

